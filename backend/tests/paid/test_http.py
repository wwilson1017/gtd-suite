def test_the_session_names_the_list_and_needs_no_x_list(new_list):
    made = new_list()
    c = made["client"]
    del c.headers["X-List"]
    res = c.get("/api/app/session")
    assert res.status_code == 200 and res.headers["cache-control"] == "no-store"
    assert res.json() == {
        "list_id": made["list_id"],
        "account_no": lists.get_list(made["list_id"])["account_no"],
        "sites_own_host": False,
        "state": "active",
        "email": None,
        "verified": False,
        "hosted": True,
        "mail": False,
        "caps": {
            "todos": 200,
            "projects": 20,
            "areas": 10,
            "brains": 1,
            "links": 3,
            "brains_label": "1",
            "links_label": "3",
            "upsell": True,
            "storage": 25_000_000,
            "storage_used": 0,
        },
        "brains": [{"id": brain.first_brain(made["list_id"]), "name": "", "folder": "brain", "status": "active"}],
        "apps": ["todo", "projects", "notes"],  # a hosted account made in Todo starts with the family
        "ai_tools": [],  # no AI tool has called yet
        "plan": {
            "pro": False,
            "tier": None,
            "status": "",
            "until": None,
            "cancels": False,
            "manageable": False,
            "free": False,
            "comp_until": None,
            "source": None,
        },
    }
    assert re.fullmatch(r"[1-9]\d{3}-\d{4}", res.json()["account_no"])
